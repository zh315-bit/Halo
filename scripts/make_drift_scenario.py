"""Generate data/SIMULATED_drift_7d.csv (AGENTS.md §12 Phase 3). SIMULATED — not measured, not real crew data.

7 mission days at 5-minute steps, same 23 columns as qr_scan_demo_clean.csv so the same adapter reads it.
  * days 1–2: scenario=baseline (the frozen personal baseline)
  * days 3–7: scenario=drift — resting/in-bed HR rises slowly, SpO2 falls slowly; everything else flat
Design target: no red flag ever fires (SpO2 stays >= 90, SBP < 180, temp < 38) and a trend `caution` with a
finite days_to_alert appears by day 4–5. Values are made up for the demo; they are not physiology claims.
Deterministic (seeded). Run: uv run python scripts/make_drift_scenario.py
"""

from __future__ import annotations

import csv
import random
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "data" / "SIMULATED_drift_7d.csv"
HEADER_NOTE = "# SIMULATED drift scenario generated by scripts/make_drift_scenario.py - not measured, not real crew data"
COLUMNS = ["demo_record_id", "crew_id", "scenario", "step", "step_minutes", "elapsed_min", "mission_day",
           "clock_time", "activity", "heart_rate_bpm", "resp_rate_bpm", "systolic_bp_mmhg", "diastolic_bp_mmhg",
           "body_temp_c", "spo2_pct", "bp_new_reading", "temp_new_reading", "estimated_fields",
           "source_hr_sleep_mood", "source_bp_temp_spo2_resp", "data_context", "measurement_origin",
           "display_label"]

DAYS, STEP_MIN, DRIFT_FROM_DAY = 7, 5, 3
HR_BASE = {"in_bed": 60.0, "resting": 72.0, "active": 98.0}
HR_DRIFT_PER_DAY = 1.5        # bpm/day from day 3 (resting + in_bed)
SPO2_BASE, SPO2_DRIFT_PER_DAY = 98.0, -1.0   # ~1 %/day is the smallest drift a 3-day window resolves (integer SpO2)


def activity(minute_of_day: int) -> str:
    h = minute_of_day // 60
    if h < 7:
        return "in_bed"
    if h == 7 or h == 18:
        return "active"
    return "resting"


def main() -> None:
    rng = random.Random(20261115)
    rows, last = [], {}
    for step in range(DAYS * 24 * 60 // STEP_MIN):
        elapsed = step * STEP_MIN
        day, mod = elapsed // 1440 + 1, elapsed % 1440
        act = activity(mod)
        drift_days = max(0.0, (elapsed / 1440 + 1) - DRIFT_FROM_DAY)     # continuous, 0 before day 3
        hr = HR_BASE[act] + rng.gauss(0, 1.5)
        if act != "active":
            hr += HR_DRIFT_PER_DAY * drift_days
        bp_new = step % 6 == 0             # BP / SpO2 / resp every 30 min
        temp_new = step % 24 == 0          # temperature every 2 h
        if bp_new or not last:
            last.update(
                systolic_bp_mmhg=round(118 + rng.gauss(0, 4)), diastolic_bp_mmhg=round(76 + rng.gauss(0, 3)),
                resp_rate_bpm=round(15 + rng.gauss(0, 1)),
                spo2_pct=round(SPO2_BASE + SPO2_DRIFT_PER_DAY * drift_days + rng.gauss(0, 0.4)))
        if temp_new or "body_temp_c" not in last:
            last["body_temp_c"] = round(36.8 + rng.gauss(0, 0.08), 1)
        rows.append({
            "demo_record_id": f"SIM_DRIFT_{step + 1:04d}", "crew_id": "SIM_CREW_DRIFT",
            "scenario": "baseline" if day < DRIFT_FROM_DAY else "drift", "step": step, "step_minutes": STEP_MIN,
            "elapsed_min": elapsed, "mission_day": day, "clock_time": f"{mod // 60:02d}:{mod % 60:02d}",
            "activity": act, "heart_rate_bpm": round(hr * 2) / 2,
            "resp_rate_bpm": float(last["resp_rate_bpm"]), "systolic_bp_mmhg": float(last["systolic_bp_mmhg"]),
            "diastolic_bp_mmhg": float(last["diastolic_bp_mmhg"]), "body_temp_c": last["body_temp_c"],
            "spo2_pct": float(last["spo2_pct"]), "bp_new_reading": bp_new, "temp_new_reading": temp_new,
            "estimated_fields": "none", "source_hr_sleep_mood": "SIMULATED", "source_bp_temp_spo2_resp": "SIMULATED",
            "data_context": "SIMULATED_drift_scenario", "measurement_origin": "SIMULATED",
            "display_label": "SIMULATED - generated drift scenario, not measured",
        })
    with OUT.open("w", newline="", encoding="utf-8") as f:
        f.write(HEADER_NOTE + "\n")
        w = csv.DictWriter(f, fieldnames=COLUMNS)
        w.writeheader()
        w.writerows(rows)
    print(f"wrote {len(rows)} rows -> {OUT}")


if __name__ == "__main__":
    main()
