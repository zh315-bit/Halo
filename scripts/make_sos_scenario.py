"""Generate data/SIMULATED_sos_event.csv (AGENTS.md §12 Phase 3). SIMULATED — not measured, not real crew data.

Same 23 columns as qr_scan_demo_clean.csv so the same adapter reads it. 5-minute steps, crew SIM_CREW_SOS:
  * days 1–2: scenario=baseline — a calm, low-noise personal baseline (no caution / alert)
  * day 3 08:00–08:30: scenario=sos_event — an acute episode while resting: SpO2 drops abruptly to 89 % at 08:05
    (red flag on that reading) and on to 86 %; HR 72 -> 118 bpm, resp 15 -> 26 /min and SBP 118 -> 138 mmHg
    (stays < 180) ramp over 30 min; temperature flat; then held for one hour (to 09:30).
    BP / SpO2 / resp are measured every 5 minutes during the event (every 30 minutes otherwise).
Design target: the FIRST alert already carries the `spo2_low` red flag (the z-band alerts of HR / resp need two
readings in a row, so they come later); `spo2_low` is the only red flag that fires; the score reaches `alert`, an SOS shows
severity_max + red_flag:spo2_low, and the proactive nudge suggests breathing_difficulty first. No `bp_crisis`, no
`fever`. Values are made up for the demo; they are not physiology claims.
Deterministic (seeded). Run: uv run python scripts/make_sos_scenario.py
"""

from __future__ import annotations

import csv
import random
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "data" / "SIMULATED_sos_event.csv"
HEADER_NOTE = ("# SIMULATED acute SOS event generated by scripts/make_sos_scenario.py - not measured, "
               "not real crew data")
COLUMNS = ["demo_record_id", "crew_id", "scenario", "step", "step_minutes", "elapsed_min", "mission_day",
           "clock_time", "activity", "heart_rate_bpm", "resp_rate_bpm", "systolic_bp_mmhg", "diastolic_bp_mmhg",
           "body_temp_c", "spo2_pct", "bp_new_reading", "temp_new_reading", "estimated_fields",
           "source_hr_sleep_mood", "source_bp_temp_spo2_resp", "data_context", "measurement_origin",
           "display_label"]
CREW = "SIM_CREW_SOS"
STEP_MIN = 5
BASELINE_DAYS = 2
EVENT_START = (BASELINE_DAYS * 24 + 8) * 60          # day 3 08:00, minutes from start
EVENT_RAMP_MIN = 30                                  # 08:00 -> 08:30
END = EVENT_START + EVENT_RAMP_MIN + 60              # held until 09:30
HR_BASE = {"in_bed": 60.0, "resting": 72.0, "active": 98.0}
SPO2_DROP_TO = 89.0                                  # first event reading after 08:00
#                 start, peak
EVENT = {"spo2_pct": (98.0, 86.0), "heart_rate_bpm": (72.0, 118.0), "resp_rate_bpm": (15.0, 26.0),
         "systolic_bp_mmhg": (118.0, 138.0), "diastolic_bp_mmhg": (76.0, 84.0)}


def activity(minute_of_day: int) -> str:
    h = minute_of_day // 60
    if h < 7:
        return "in_bed"
    if h == 7 or h == 18:
        return "active"
    return "resting"


def event_fraction(elapsed: int) -> float:
    """0 before the event, ramps 0 -> 1 over EVENT_RAMP_MIN, then 1."""
    if elapsed < EVENT_START:
        return 0.0
    return min(1.0, (elapsed - EVENT_START) / EVENT_RAMP_MIN)


def main() -> None:
    rng = random.Random(20261116)
    rows, last = [], {}
    for step in range(END // STEP_MIN + 1):
        elapsed = step * STEP_MIN
        day, mod = elapsed // 1440 + 1, elapsed % 1440
        act = activity(mod)
        f = event_fraction(elapsed)
        in_event = elapsed >= EVENT_START
        hr = HR_BASE[act] + rng.gauss(0, 1.0)
        if in_event:
            lo, hi = EVENT["heart_rate_bpm"]
            hr = lo + (hi - lo) * f + rng.gauss(0, 1.0)
        bp_new = in_event or step % 6 == 0               # every 5 min in the event, else every 30 min
        temp_new = step % 24 == 0                        # temperature every 2 h
        if bp_new or not last:
            base = {"spo2_pct": 98.0 + rng.gauss(0, 0.3), "resp_rate_bpm": 15.0 + rng.gauss(0, 0.6),
                    "systolic_bp_mmhg": 118.0 + rng.gauss(0, 3), "diastolic_bp_mmhg": 76.0 + rng.gauss(0, 2)}
            if in_event:
                for m, (lo, hi) in EVENT.items():
                    if m in base:
                        base[m] = lo + (hi - lo) * f + rng.gauss(0, 0.3)
                if f > 0:                                # abrupt desaturation: 89 at 08:05, then on to 86
                    base["spo2_pct"] = SPO2_DROP_TO - (SPO2_DROP_TO - EVENT["spo2_pct"][1]) * f
            last.update(spo2_pct=round(base["spo2_pct"]), resp_rate_bpm=round(base["resp_rate_bpm"]),
                        systolic_bp_mmhg=round(base["systolic_bp_mmhg"]),
                        diastolic_bp_mmhg=round(base["diastolic_bp_mmhg"]))
        if temp_new or "body_temp_c" not in last:
            last["body_temp_c"] = round(36.8 + rng.gauss(0, 0.05), 1)
        rows.append({
            "demo_record_id": f"SIM_SOS_{step + 1:04d}", "crew_id": CREW,
            "scenario": "sos_event" if in_event else "baseline", "step": step, "step_minutes": STEP_MIN,
            "elapsed_min": elapsed, "mission_day": day, "clock_time": f"{mod // 60:02d}:{mod % 60:02d}",
            "activity": act, "heart_rate_bpm": round(hr * 2) / 2,
            "resp_rate_bpm": float(last["resp_rate_bpm"]), "systolic_bp_mmhg": float(last["systolic_bp_mmhg"]),
            "diastolic_bp_mmhg": float(last["diastolic_bp_mmhg"]), "body_temp_c": last["body_temp_c"],
            "spo2_pct": float(last["spo2_pct"]), "bp_new_reading": bp_new, "temp_new_reading": temp_new,
            "estimated_fields": "none", "source_hr_sleep_mood": "SIMULATED", "source_bp_temp_spo2_resp": "SIMULATED",
            "data_context": "SIMULATED_sos_event_scenario", "measurement_origin": "SIMULATED",
            "display_label": "SIMULATED - generated acute event, not measured",
        })
    with OUT.open("w", newline="", encoding="utf-8") as fh:
        fh.write(HEADER_NOTE + "\n")
        w = csv.DictWriter(fh, fieldnames=COLUMNS)
        w.writeheader()
        w.writerows(rows)
    print(f"wrote {len(rows)} rows -> {OUT}")


if __name__ == "__main__":
    main()
